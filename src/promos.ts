import { InlineKeyboard } from "grammy";
import { env, mainBotLink } from "./config.js";

export interface Promo {
  /** Stable id — used as the deep-link payload for funnel tracking. */
  id: string;
  label: string;
  text: string;
  extraButtons?: Array<{ label: string; url: string }>;
}

const CTA_ORDER = "🚀 ثبت سفارش سریع";
const CTA_CONSULT = "💬 مشاورهٔ رایگان";
const CTA_SITE = `🌐 ${env.siteUrl.replace(/^https?:\/\//, "")}`;

function baseKeyboard(promo: Promo): InlineKeyboard {
  const keyboard = new InlineKeyboard()
    .url(CTA_ORDER, mainBotLink(promo.id))
    .url(CTA_CONSULT, env.supportUrl)
    .row()
    .url(CTA_SITE, env.siteUrl);
  for (const button of promo.extraButtons ?? []) {
    keyboard.row().url(button.label, button.url);
  }
  return keyboard;
}

